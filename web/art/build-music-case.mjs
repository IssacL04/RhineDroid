/** V0.4.0 native-size album case. Rebuild: node art/build-music-case.mjs */
import fs from "node:fs/promises";
import { createHash } from "node:crypto";
import * as THREE from "three";
import { mergeGeometries, mergeVertices } from "three/addons/utils/BufferGeometryUtils.js";
import { GLTFExporter } from "three/addons/exporters/GLTFExporter.js";
import { MUSIC_MODEL, MUSIC_COVER, MUSIC_CASE_LAYERS, configureMusicGlass } from "../src/music-model.ts";

// The exporter only needs FileReader for its in-memory Blob conversion.
globalThis.FileReader ??= class {
  readAsArrayBuffer(blob) {
    blob.arrayBuffer().then((result) => { this.result = result; this.onloadend?.(); });
  }
};

const root = new URL("../", import.meta.url);
const parts = new Map(["Frosted_Polymer", "Ivory_Edges", "Optical_Diffuser"].map(name => [name, []]));
const construction = [];

function roundedRect(width, height, radius) {
  const x = -width / 2, y = -height / 2, r = radius;
  const shape = new THREE.Shape();
  shape.moveTo(x + r, y);
  shape.lineTo(x + width - r, y);
  shape.quadraticCurveTo(x + width, y, x + width, y + r);
  shape.lineTo(x + width, y + height - r);
  shape.quadraticCurveTo(x + width, y + height, x + width - r, y + height);
  shape.lineTo(x + r, y + height);
  shape.quadraticCurveTo(x, y + height, x, y + height - r);
  shape.lineTo(x, y + r);
  shape.quadraticCurveTo(x, y, x + r, y);
  return shape;
}

function slab(name, surface, center, size, { radius = 0.028, bevel = 0.004, hole } = {}) {
  const [width, height, depth] = size;
  const shape = roundedRect(width - bevel * 2, height - bevel * 2, Math.max(0.001, radius - bevel));
  if (hole) {
    const inner = roundedRect(hole[0] + bevel * 2, hole[1] + bevel * 2, radius);
    const path = new THREE.Path(inner.getPoints(3).reverse());
    shape.holes.push(path);
  }
  const geometry = new THREE.ExtrudeGeometry(shape, {
    depth: depth - bevel * 2, steps: 1,
    bevelEnabled: true, bevelSegments: 1, bevelSize: bevel, bevelThickness: bevel,
    curveSegments: 3,
  }).translate(center[0], center[1], center[2] - depth / 2 + bevel);
  geometry.clearGroups();
  parts.get(surface).push(geometry);
  construction.push({ name, surface, center, size, radius, bevel, ...(hole ? { hole } : {}) });
}

// A broad, uninterrupted thin lid; the artwork seats behind it. The left edge
// meets a separate, much rougher spine instead of stretching the old solid box.
slab("Thin frosted lid", "Frosted_Polymer", [0.175, 1.85, 0.061], [4.10, 3.35, 0.018]);
slab("High-frost binding spine", "Ivory_Edges", [-2.05, 1.85, 0], [0.35, 3.35, 0.14], { radius: 0.034, bevel: 0.009 });
// A recessed groove on each side of the spine is actual geometry. The front
// step catches the broad soft light; it is not an extra opaque stripe on art.
slab("Spine shoulder", "Ivory_Edges", [-1.884, 1.85, 0.015], [0.024, 3.24, 0.082], { radius: 0.01, bevel: 0.003 });
slab("Rear tray", "Optical_Diffuser", [0.175, 1.85, -0.05], [4.10, 3.35, 0.036]);
// The perimeter seat makes the cover's physical recess readable at grazing
// angles. Its open centre never cuts across the inserted square artwork.
slab("Open perimeter seat", "Optical_Diffuser", [0.175, 1.85, -0.003], [4.10, 3.35, 0.098], {
  radius: 0.035, bevel: 0.004, hole: [3.95, 3.20],
});
// Two short paper stops sit outside the art. They keep the object reading as
// an album holder while maintaining the quiet manufactured reference language.
for (const y of [0.242, 3.458]) slab("Paper stop", "Optical_Diffuser", [0.175, y, 0.014], [0.44, 0.026, 0.042], { radius: 0.008, bevel: 0.003 });

const scene = new THREE.Group();
scene.name = "Rhine_Music_Case_V040";
scene.userData = { version: "0.4.0", dimensions: MUSIC_MODEL, cover: MUSIC_COVER, layers: MUSIC_CASE_LAYERS, construction };
let triangles = 0;
for (const [surface, geometries] of parts) {
  const geometry = mergeVertices(mergeGeometries(geometries), 1e-6);
  geometry.userData.musicDimensions = true;
  const material = new THREE.MeshPhysicalMaterial({ name: surface });
  configureMusicGlass(surface, material);
  // Functions and runtime palette caches do not belong in the exported source.
  material.userData = {};
  const mesh = new THREE.Mesh(geometry, material);
  mesh.name = `Music_Case_V040__${surface}`;
  mesh.userData = { musicCdShell: true, musicDimensions: true, surface };
  scene.add(mesh);
  triangles += geometry.index.count / 3;
}
const data = await new GLTFExporter().parseAsync(scene, { binary: true, onlyVisible: true });
const bytes = Buffer.from(data);
await fs.writeFile(new URL("public/assets/music-case-v040.glb", root), bytes);
const digest = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
await fs.writeFile(new URL("src/music-cd-asset.ts", root), `// Generated by art/build-music-case.mjs; the V0.3 source asset is preserved.\nexport const MUSIC_CD_ASSET = "assets/music-case-v040.glb?v=${digest}";\n`);
await fs.writeFile(new URL("art/music-case-v040.json", root), JSON.stringify({
  version: "0.4.0", generator: "art/build-music-case.mjs", units: "scene units", dimensions: MUSIC_MODEL,
  cover: MUSIC_COVER, layers: MUSIC_CASE_LAYERS, construction, meshes: scene.children.length,
  triangles, bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex"),
}, null, 2) + "\n");
console.log(`Album case V0.4.0: ${scene.children.length} instanced batches, ${triangles} triangles, ${bytes.length} bytes, ${digest}.`);
